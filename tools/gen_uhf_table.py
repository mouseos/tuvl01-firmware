"""Generate src/tuner_uhf_table.c from per-channel tune profile JSON files.

Usage: python tools/gen_uhf_table.py DIR   (DIR holds uhf-ch13-full.json .. uhf-ch52-full.json)

Each JSON is a `tune.py` profile (see tools/tune.py). The firmware builds the partial
(one-segment) profile from the full one, so only the full-segment files are read;
the dtvset of a full profile must be 0x16 and tncop6 must be 0.
"""
import json,pathlib,sys
FIRST,LAST=13,52
def main():
    src=pathlib.Path(sys.argv[1]);rows=[]
    for ch in range(FIRST,LAST+1):
        p=json.loads((src/f'uhf-ch{ch}-full.json').read_text(encoding='utf-8-sig'))
        if p['mode']!='uhf-native-candidate' or p['dtvset']!=0x16 or p['tncop6']!=0:raise SystemExit(f'ch{ch}: unexpected profile')
        if p['rf_khz']!=473143+6000*(ch-FIRST):raise SystemExit(f'ch{ch}: unexpected frequency')
        rows.append(p)
    out=['/* SPDX-License-Identifier: MIT',
         ' * UHF channel 13..52 tuner constants. GENERATED by tools/gen_uhf_table.py from',
         ' * tune profiles; do not edit by hand. Frequency is 473143+6000*(ch-13) kHz.',
         ' * The values are hardware inputs for the MN885521 and remain experimental. */',
         '#include "tuner_uhf.h"',
         'const struct tuner_uhf_entry tuner_uhf_table[TUNER_UHF_COUNT]={',
         '    /* fad, nco, p_k, tncop1, tncop2, tncop3, tncop4, tncop7, adclksel, p_m, sysset */']
    for ch,p in zip(range(FIRST,LAST+1),rows):
        out.append('    {%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d}, /* ch%d */'%(p['fad'],p['nco'],p['p_k'],p['tncop1'],p['tncop2'],
            p['tncop3'],p['tncop4'],p['tncop7'],p['adclksel'],p['p_m'],p['sysset'],ch))
    out.append('};')
    (pathlib.Path(__file__).resolve().parents[1]/'src'/'tuner_uhf_table.c').write_text('\n'.join(out)+'\n',encoding='utf-8')
    print('wrote',len(rows),'channels')
main()
